#!/usr/bin/env python3
"""Build the flashcard decks from template.v2.html + card data, with EVERY look baked in from the Brand Kit.

Usage:
  python3 build.v2.py --kit <folder with brands.json and the logo files> [--cards cards.json] [--pics pictures.json]
                      [--template template.v2.html] [--out out] [--repo <goodman-assets clone>]

What it does (Phase 2 of the Extras Library, 17 Oct 2026):
  * reads brands.json (Drive › 30 Resources › Brand Kit – stage a copy of the folder, or point --kit at it);
  * for every kit block (globus, goodman, neutral, … any block with a 'palette') writes the deck's CSS variables for the
    light and the dark theme, so  ?brand=<key>  switches the look at run time without a rebuild;
  * copies each kit's web logo (logo.webFile, else logo.pngFile, else logo.file) from the kit folder into the deck's img/;
  * writes out/<slug>/index.html and, with --repo, straight into <repo>/flashcards/<slug>/ (index.html + img/*-logo.*).
A new school = one block in brands.json + one run of this script. 'plain' in an old link still works (alias of 'neutral').
"""
import argparse, colorsys, copy, json, os, shutil, sys

ap = argparse.ArgumentParser()
ap.add_argument('--kit', required=True)
ap.add_argument('--cards', default='cards.json')
ap.add_argument('--pics', default='pictures.json')
ap.add_argument('--template', default='template.v2.html')
ap.add_argument('--out', default='out')
ap.add_argument('--repo', default='')
A = ap.parse_args()

KIT = json.load(open(os.path.join(A.kit, 'brands.json'), encoding='utf-8'))
BRANDS = {k: v for k, v in KIT.items() if not k.startswith('_') and isinstance(v, dict) and v.get('palette')}
if not BRANDS: sys.exit('brands.json has no kit blocks')
T = open(A.template, encoding='utf-8').read()
cards = json.load(open(A.cards, encoding='utf-8'))
pics = json.load(open(A.pics, encoding='utf-8'))

DECKS = {
 'atotal': dict(id='atotal-fc', brand='globus', title='Atotal Revision Flashcards', eyebrow='Atotal group · Final test revision',
               h1='Revision flashcards', sub='Everything from the course, lessons 1–99', subhu='Ismétlés a záróvizsgára', lessons=True),
 'a1-a2': dict(id='a1a2-fc', brand='neutral', title='A1–A2 Revision Flashcards', eyebrow='English A1–A2 · Revision',
               h1='Revision flashcards', sub='Work, travel, hotels, restaurants and everyday English', subhu='Ismétlő szókártyák A1–A2 szinten', lessons=False),
}

# ---------- colours ----------
def hex2rgb(h):
    h = h.lstrip('#'); return tuple(int(h[i:i+2], 16) / 255 for i in (0, 2, 4))
def rgb2hex(r, g, b): return '#%02X%02X%02X' % tuple(round(max(0, min(1, x)) * 255) for x in (r, g, b))
def with_l(h, l, s_mul=1.0):
    hh, ll, ss = colorsys.rgb_to_hls(*hex2rgb(h)); return rgb2hex(*colorsys.hls_to_rgb(hh, l, min(1, ss * s_mul)))
def mix(a, b, t):
    ra, rb = hex2rgb(a), hex2rgb(b); return rgb2hex(*[ra[i] * (1 - t) + rb[i] * t for i in range(3)])
def is_hex(v): return isinstance(v, str) and v.startswith('#') and len(v) in (4, 7)

def look(b):
    P, w = b.get('palette', {}), b.get('web', {})
    col = lambda v: (P.get(v) if v in P else v) or ''
    acc, accd = col(w.get('accent')), col(w.get('accentDark'))
    if not is_hex(acc): sys.exit('kit block without a usable web.accent: ' + json.dumps(w)[:80])
    if not is_hex(accd): accd = with_l(acc, max(0.12, colorsys.rgb_to_hls(*hex2rgb(acc))[1] - 0.12))
    tint = col(w.get('selectBg')) or col(w.get('exampleBg')) or col(w.get('panel')) or mix(acc, '#FFFFFF', 0.9)
    if not is_hex(tint): tint = mix(acc, '#FFFFFF', 0.9)
    light = dict(c=acc, d=accd, t=tint)
    l_acc = colorsys.rgb_to_hls(*hex2rgb(acc))[1]
    dark = dict(c=with_l(acc, 0.64), d=with_l(acc, 0.76), t=mix(acc, '#18181B', 0.78))   # dark theme: the same hue, lifted to read on a dark page
    return light, dark

def brand_css():
    out = ['/* brand accents – generated by build.v2.py from brands.json; Globus stays the default in :root above */']
    for k, b in BRANDS.items():
        L, D = look(b)
        v = lambda x: '--crimson:%s;--crimson-dark:%s;--crimson-tint:%s' % (x['c'], x['d'], x['t'])
        out.append(':root[data-brand="%s"]{%s}' % (k, v(L)))
        out.append('@media (prefers-color-scheme: dark){:root[data-brand="%s"]:not([data-theme="light"]){%s}}' % (k, v(D)))
        out.append(':root[data-brand="%s"][data-theme="dark"]{%s}' % (k, v(D)))
    return '\n'.join(out)

# ---------- logos ----------
def logo_file(b):
    L = b.get('logo', {})
    for key in ('deckFile', 'webFile', 'pngFile', 'file'):   # v3: deckFile = the picture for the deck's top corner (e.g. the Goodman flashcard mascot)
        f = L.get(key)
        if f and os.path.exists(os.path.join(A.kit, f)): return f
    return ''
LOGOS = {}
for k, b in BRANDS.items():
    f = logo_file(b)
    if f: LOGOS[k] = ['img/%s-logo%s' % (k, os.path.splitext(f)[1].lower()), b.get('logo', {}).get('alt') or b.get('name') or k, f,
                      1 if (f == b.get('logo', {}).get('deckFile') and b.get('logo', {}).get('deckRound')) else 0]
    else: print('note: no logo file for', k, '- the deck hides the logo plate in that look')

js = lambda o: json.dumps(o, ensure_ascii=False).replace('</', '<\\/')
def page(cfg):
    d = copy.deepcopy(cards)
    if not cfg['lessons']:
        for s in d['sets']:
            for c in s['cards']: c.pop('lesson', None)
    deck = {k: cfg[k] for k in ('id', 'brand')}
    out = T
    for k, v in (('__TITLE__', cfg['title']), ('__EYEBROW__', cfg['eyebrow']), ('__H1__', cfg['h1']), ('__SUB__', cfg['sub']), ('__SUBHU__', cfg['subhu'])):
        out = out.replace(k, v)
    out = out.replace('/*__BRAND_CSS__*/', brand_css())
    out = out.replace('__BRAND_KEYS__', js(list(BRANDS))).replace('__BRAND_LOGOS__', js({k: [v[0], v[1], v[3]] for k, v in LOGOS.items()}))
    return out.replace('__DECK__', js(deck)).replace('__DATA__', js(d)).replace('__PICS__', js(pics))
def standalone(p):
    return ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n<meta name="robots" content="noindex">\n'
            + p.replace('<style>', '<style>\n*,*::before,*::after{box-sizing:border-box}body{margin:0}img{max-width:100%}', 1).replace('<div class="wrap">', '</head>\n<body>\n<div class="wrap">', 1) + '\n</body>\n</html>\n')

for slug, cfg in DECKS.items():
    p = standalone(page(cfg))
    targets = [os.path.join(A.out, slug)] + ([os.path.join(A.repo, 'flashcards', slug)] if A.repo else [])
    for t in targets:
        os.makedirs(os.path.join(t, 'img'), exist_ok=True)
        open(os.path.join(t, 'index.html'), 'w', encoding='utf-8').write(p)
        for k, (rel, alt, src, rnd) in LOGOS.items(): shutil.copyfile(os.path.join(A.kit, src), os.path.join(t, rel))
print('built', list(DECKS), 'looks', list(BRANDS), 'logos', {k: v[0] for k, v in LOGOS.items()})
